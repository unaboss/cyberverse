// Live mode, draft: turns one organisation at one maturity level into real
// containers on the user's PC. NOT APPROVED TO RUN YET: live mode touches
// networking, so it waits on its DECISIONS.md entry. The generator only writes
// files for review.
//
// What it builds:
// - one Docker network per zone, plus "internet" for the attacker, all
//   `internal: true` so nothing in the lab can reach the real internet;
// - a gateway container (gw) on every zone at .1 that routes between zones and
//   enforces the organisation's zone policy with iptables (firewall.sh);
// - routes.sh, which points each machine's default route at gw by borrowing
//   its network namespace from a helper container (the vulnerable images do
//   not ship the `ip` tool);
// - the machines that have a live image, at their lab addresses;
// - Suricata (nids) on the host network, sniffing the zones the org's NIDS
//   controls cover, writing eve.json for src/live/eve.ts;
// - a Kali box on the internet network at the first attacker address.

import type { WorldBundle } from '../world/load.ts';
import { resolveOrg, type ResolvedOrg } from '../world/resolve.ts';
import { intToIp, ipToInt, parseCidr } from '../world/net.ts';
import type { Level } from '../world/types.ts';

export interface ComposeOptions {
  level?: Level;
  /** Also run machines with no live image, as idle placeholders, so the map is complete. */
  placeholders?: boolean;
}

export interface LivePlan {
  project: string;
  files: { path: string; content: string }[];
  machines: { key: string; ip: string; image: string; placeholder: boolean }[];
  warnings: string[];
}

const GATEWAY_IMAGE = 'nicolaka/netshoot:v0.13';
const SURICATA_IMAGE = 'jasonish/suricata:7.0.7';
const KALI_IMAGE = 'kalilinux/kali-rolling:latest';
const PLACEHOLDER_IMAGE = 'alpine:3.20';

function hostAt(cidr: string, n: number): string {
  const { base } = parseCidr(cidr);
  return intToIp(base + n);
}

/** Linux interface names are at most 15 characters. */
export function bridgeName(org: string, zone: string): string {
  return `cl-${org.slice(0, 4)}-${zone}`.slice(0, 15);
}

function yamlString(value: string): string {
  return JSON.stringify(value);
}

function zoneCidr(org: ResolvedOrg, zone: string): string | undefined {
  return org.zones.find((z) => z.id === zone)?.cidr;
}

export function buildLivePlan(bundle: WorldBundle, orgId: string, opts: ComposeOptions = {}): LivePlan {
  const org = resolveOrg(bundle, orgId, opts.level);
  const internet = bundle.miniverse.internet;
  const project = `cyberverse-${orgId}-l${org.level}`;
  const warnings: string[] = [];
  const lines: string[] = [];

  lines.push(
    '# GENERATED by `npm run compose`. Do not edit by hand: change the world files.',
    '# DRAFT. Live mode is not approved to run yet (see DECISIONS.md, live mode).',
    `# ${org.def.name} at maturity level ${org.level}. Every network is internal: no lab`,
    '# container can reach the real internet. Lab addresses only (10.88.0.0/16).',
    `name: ${project}`,
    '',
    'networks:',
  );
  const networks: { id: string; cidr: string }[] = [{ id: 'internet', cidr: internet.cidr }, ...org.zones.map((z) => ({ id: z.id, cidr: z.cidr }))];
  for (const net of networks) {
    lines.push(
      `  ${net.id}:`,
      '    internal: true',
      '    driver: bridge',
      '    driver_opts:',
      `      com.docker.network.bridge.name: ${bridgeName(orgId, net.id)}`,
      '    ipam:',
      '      config:',
      `        - subnet: ${net.cidr}`,
      `          gateway: ${hostAt(net.cidr, 254)}`,
    );
  }

  lines.push('', 'services:');

  // Gateway and policy.
  lines.push(
    '  gw:',
    `    image: ${GATEWAY_IMAGE}`,
    '    hostname: gw',
    '    cap_add: [NET_ADMIN]',
    '    sysctls:',
    '      net.ipv4.ip_forward: "1"',
    '    volumes:',
    '      - ./firewall.sh:/firewall.sh:ro',
    '    command: ["sh", "-c", "sh /firewall.sh && exec sleep infinity"]',
    '    networks:',
  );
  for (const net of networks) {
    lines.push(`      ${net.id}: { ipv4_address: ${hostAt(net.cidr, 1)} }`);
  }

  // Machines.
  const machines: LivePlan['machines'] = [];
  const reserved = new Set(['gw', 'kali', 'nids']);
  for (const sys of org.systems) {
    if (sys.live?.image === SURICATA_IMAGE) {
      // The org's IDS box is played by the host-network sensor below, which can see every bridge.
      continue;
    }
    if (reserved.has(sys.id)) {
      warnings.push(`${sys.key}: the name ${sys.id} is reserved in live mode; skipped.`);
      continue;
    }
    const placeholder = !sys.live;
    if (placeholder && !opts.placeholders) {
      continue;
    }
    if (!zoneCidr(org, sys.zone)) {
      warnings.push(`${sys.key}: zone ${sys.zone} does not exist at level ${org.level}; skipped.`);
      continue;
    }
    const image = sys.live?.image ?? PLACEHOLDER_IMAGE;
    machines.push({ key: sys.key, ip: sys.ip, image, placeholder });
    lines.push(
      `  ${sys.id}:`,
      `    image: ${yamlString(image)}`,
      `    hostname: ${sys.hostname}`,
      `    domainname: ${org.def.domain}`,
      '    labels:',
      `      cyberverse.system: ${yamlString(sys.key)}`,
      `      cyberverse.placeholder: ${yamlString(String(placeholder))}`,
    );
    if (sys.live?.env && Object.keys(sys.live.env).length > 0) {
      lines.push('    environment:');
      for (const [key, value] of Object.entries(sys.live.env)) {
        lines.push(`      ${key}: ${yamlString(value)}`);
      }
    }
    if (placeholder) {
      lines.push('    command: ["sleep", "infinity"]');
    } else if (sys.live?.command) {
      lines.push(`    command: ${yamlString(sys.live.command)}`);
    }
    lines.push('    networks:', `      ${sys.zone}: { ipv4_address: ${sys.ip} }`, '    depends_on: [gw]');
  }
  if (machines.length === 0) {
    warnings.push(`No system in ${orgId} has a live image at level ${org.level}. Use --placeholders to lay out the network anyway.`);
  }

  // Attacker box.
  const attackerIp = internet.attackerPool[0]!;
  lines.push(
    '  kali:',
    `    image: ${KALI_IMAGE}`,
    '    hostname: kali',
    '    command: ["sleep", "infinity"]',
    '    networks:',
    `      internet: { ipv4_address: ${attackerIp} }`,
    '    depends_on: [gw]',
  );

  // Network IDS on the bridges the NIDS controls cover.
  const nidsZones = new Set<string>();
  for (const control of org.controls) {
    const on = control.lab ? control.lab === 'on' : control.status === 'in-place';
    if (on && control.sensor?.type === 'nids') {
      for (const zone of control.sensor.covers) {
        if (zoneCidr(org, zone)) {
          nidsZones.add(zone);
        }
      }
    }
  }
  if (nidsZones.size > 0) {
    const ifaces = [...nidsZones].flatMap((zone) => ['-i', bridgeName(orgId, zone)]);
    lines.push(
      '  nids:',
      `    image: ${SURICATA_IMAGE}`,
      '    network_mode: host',
      '    cap_add: [NET_ADMIN, NET_RAW, SYS_NICE]',
      '    volumes:',
      '      - ./logs:/var/log/suricata',
      `    command: ${JSON.stringify(ifaces)}`,
      '    depends_on: [gw]',
    );
  } else {
    warnings.push(`No network IDS covers ${orgId} at level ${org.level}, so live mode has no Suricata sensor.`);
  }

  return {
    project,
    files: [
      { path: 'docker-compose.yml', content: `${lines.join('\n')}\n` },
      { path: 'firewall.sh', content: firewallScript(org, internet.cidr) },
      { path: 'routes.sh', content: routesScript(project, org, machines, internet.cidr, attackerIp) },
    ],
    machines,
    warnings,
  };
}

/** iptables rules for gw, straight from the organisation's zone policy. */
export function firewallScript(org: ResolvedOrg, internetCidr: string): string {
  const out = [
    '#!/bin/sh',
    `# GENERATED zone policy for ${org.def.name}, level ${org.level}. Runs inside gw.`,
    'set -e',
    'iptables -P FORWARD DROP',
    'iptables -F FORWARD',
    'iptables -A FORWARD -m conntrack --ctstate ESTABLISHED,RELATED -j ACCEPT',
  ];
  const cidrOf = (zone: string): string | undefined => (zone === 'internet' ? internetCidr : zoneCidr(org, zone));
  for (const flow of org.policy) {
    const src = cidrOf(flow.src);
    const dst = cidrOf(flow.dst);
    if (!src || !dst) {
      continue;
    }
    const note = flow.note ? `  # ${flow.note.replace(/\n/g, ' ')}` : '';
    if (flow.ports === 'any') {
      out.push(`iptables -A FORWARD -s ${src} -d ${dst} -j ACCEPT${note}`);
      continue;
    }
    for (let i = 0; i < flow.ports.length; i += 15) {
      const ports = flow.ports.slice(i, i + 15).join(',');
      out.push(`iptables -A FORWARD -s ${src} -d ${dst} -p tcp -m multiport --dports ${ports} -j ACCEPT${note}`);
    }
  }
  out.push('# Learner blocks are inserted above this line at run time (iptables -I FORWARD 1 -s <ip> -j DROP).', '');
  return out.join('\n');
}

/** Point every machine's default route at gw, from outside the machine. */
function routesScript(project: string, org: ResolvedOrg, machines: LivePlan['machines'], internetCidr: string, attackerIp: string): string {
  const out = [
    '#!/bin/sh',
    `# GENERATED. Run after \`docker compose -p ${project} up -d\`.`,
    '# Borrows each container\'s network namespace from a helper image, so the',
    '# lab images do not need the ip tool.',
    'set -e',
    'route() {',
    `  docker run --rm --net "container:$1" --cap-add NET_ADMIN ${GATEWAY_IMAGE} ip route replace default via "$2"`,
    '}',
  ];
  for (const m of machines) {
    const sys = org.systems.find((s) => s.key === m.key)!;
    const cidr = zoneCidr(org, sys.zone)!;
    out.push(`route ${project}-${sys.id}-1 ${hostAt(cidr, 1)}`);
  }
  out.push(`route ${project}-kali-1 ${hostAt(internetCidr, 1)}  # attacker at ${attackerIp}`, '');
  return out.join('\n');
}

/** True if every address in the plan sits inside the lab range. */
export function planInsideLab(plan: LivePlan, labRange: string): boolean {
  const { base, size } = parseCidr(labRange);
  return plan.machines.every((m) => {
    const n = ipToInt(m.ip);
    return n >= base && n < base + size;
  });
}
